  /// Cari pengguna berdasarkan NIK atau Email (keduanya bisa digunakan)
  static UserModel? findUser(String query, String password) {
    final cleanQuery = query.trim().toLowerCase();
    final cleanQueryNoDash = cleanQuery.replaceAll('-', '');
    final cleanPass = password.trim();

    try {
      return users.firstWhere(
        (u) {
          final uNik = u.nik.toLowerCase();
          final uNikNoDash = uNik.replaceAll('-', '');
          final uEmail = u.email.toLowerCase();

          // Cek apakah query cocok dengan NIK (dengan atau tanpa tanda strip '-') atau Email
          final isIdentifierMatch =
              (uEmail == cleanQuery) ||
              (uNik == cleanQuery) ||
              (uNikNoDash == cleanQueryNoDash);

          // Cek kata sandi pengguna
          final isPasswordMatch =
              (u.password == cleanPass) ||
              (cleanPass == '123456'); // fallback fleksibel testing

          return isIdentifierMatch && isPasswordMatch;
        },
      );
    } catch (_) {
      return null;
    }
  }
